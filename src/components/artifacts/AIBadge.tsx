import { Sparkles } from "lucide-react";
import { Badge } from "@/components/ui";
import { cn } from "@/lib/utils";
import type { AiProviderName } from "@/lib/db/types";

/**
 * Provenance badge for AI-generated artifacts (spec 20.10 + 36): always
 * shows which provider produced the draft. Mock drafts are labeled mock —
 * the app never claims a real model was called when it was not.
 */

const PROVIDER_LABELS: Record<AiProviderName, string> = {
  gemini: "Gemini",
  openai: "OpenAI",
  mock: "Mock",
};

export function AIBadge({
  provider,
  model,
  className,
}: {
  provider: AiProviderName;
  /** Optional in compact contexts (list views show provider only). */
  model?: string;
  className?: string;
}) {
  const isMock = provider === "mock";
  const label = isMock
    ? "AI draft · mock"
    : `AI draft · ${PROVIDER_LABELS[provider]}`;
  return (
    <Badge
      tone={isMock ? "warning" : "accent"}
      title={`Generated by the ${PROVIDER_LABELS[provider]} provider${
        model ? ` (${model})` : ""
      }${isMock ? " — deterministic sample draft, no real model was called" : ""}`}
      className={cn("gap-1", className)}
    >
      <Sparkles className="size-3" aria-hidden="true" />
      {label}
    </Badge>
  );
}
